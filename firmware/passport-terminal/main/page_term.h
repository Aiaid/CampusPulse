// page_term.h —— 记录终端页面：选择地点 → 录入（停车范围 / 候梯计时）→
// 确认 → 提交 → 结果。三按键直绘界面（ui_mini）。
//
// 按键语义：
//   ▲/▼ 短按     移动焦点 / 调整数值（长按 ±10 步进）
//   OK  短按     进入 / 确认 / 提交 / 返回
//   OK  长按     在地点列表页：重新拉取服务器地点列表
//   OK  双击     预留（未绑定）
//
// 设计约束（web-api-v0 与 AGENTS.md）：
//   * 本地保存成功与云端确认分开显示：提交结果页明确区分
//     「已提交（服务器确认）」与「已入队待提交（仅本地）」。
//   * 时间未同步时不允许提交：observed_at 必须是真实的 UTC 观察时刻，
//     不能用未同步的时钟编造。
//   * 空记录不代表 0：界面只陈述已发生的事实，不补全未观测的状态。
#pragma once

#include "bsp_button.h"

// 启动页面任务（幂等）。必须先 ui_init()、obs_store_init() 成功。
void page_term_start(void);

// 按键入口：由主输入任务调用（非按键回调上下文，允许做 SPI 绘制）。
void page_term_key(bsp_btn_t btn, bsp_btn_ev_t ev);
