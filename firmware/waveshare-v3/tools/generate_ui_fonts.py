"""Reproduce the native 12/14/16px CampusPulse V3 LVGL 9.5 text fonts.

uv run firmware/waveshare-v3/tools/generate_ui_fonts.py --font /path/to/font.otf
Add --check to compare generated files without writing. --scan verifies that all
non-ASCII characters in a UTF-8 UI source are covered. --preview writes a BMP
contact sheet for local inspection. Source input is pinned by SHA-256.
"""
