FONT_SHA256 = "b5f0d1a190a7f9b43c310a8850630af12553df32c4c050543f9059732d9b4c0a"
SIZES = (12, 14, 16)
# Keep the reviewed raw-UI baseline plus the three V3 operational pages.
# Include status/failure transitions so changing state never drops a glyph.
