import json
import math
from pathlib import Path

import fontTools
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont, features, __version__ as pillow_version

ROOT = Path(__file__).resolve().parents[1]
SOURCE_MANIFEST = ROOT.parent / "waveshare-raw/fonts/manifest.json"
REUSED_GENERATOR = ROOT.parent / "waveshare-raw/tools/generate_ui_fonts.py"
