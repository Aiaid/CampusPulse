CODEPOINTS = sorted(set(range(32, 127)) | {ord(c) for c in UI_TEXT})
HEADER = """// SPDX-License-Identifier: OFL-1.1
// Copyright (c) 2014-2021 Adobe (http://www.adobe.com/).
// CampusPulse V3 UI: native-size raster subsets of Noto Sans CJK SC Bold 2.004.
// See ../fonts/{manifest.json,OFL.txt,COPYRIGHT.txt}.
// Generated by tools/generate_ui_fonts.py; do not edit by hand.
"""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def array(data: bytes | list[int]) -> str:
    return "\n".join(
        "    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 16]) + ","
        for i in range(0, len(data), 16)
    )


def raster(font: ImageFont.FreeTypeFont, cp: int) -> tuple[Image.Image, int, int, int]:
    # Direct rasterization at the requested pixel size; no bitmap rescaling.
    canvas = Image.new("L", (96, 96), 0)
    ImageDraw.Draw(canvas).text((24, 48), chr(cp), font=font, anchor="ls", fill=255)
    canvas = canvas.point(lambda v: min(15, (v + 8) // 17))
    box = canvas.getbbox()
    advance = max(1, math.ceil(font.getlength(chr(cp))))
    if not box:
        return Image.new("L", (0, 0)), 0, 0, advance
    glyph = canvas.crop(box)
    # Avoid negative left bearings, so every glyph fits in its own advance.
    x = max(0, box[0] - 24)
    advance = max(advance, x + glyph.width)
    return glyph, x, box[3] - 48, advance


def pack(image: Image.Image) -> bytes:
    # LVGL fmt_txt stride=0 packs pixels continuously, MS nibble first.
    pixels = list(image.get_flattened_data())
    return bytes((pixels[i] << 4) | (pixels[i + 1] if i + 1 < len(pixels) else 0)
                 for i in range(0, len(pixels), 2))


def generate(font_path: Path) -> tuple[dict[Path, str], dict, dict]:
    source = font_path.read_bytes()
    if sha256(source) != FONT_SHA256:
        raise ValueError("Source font differs from reviewed official SHA-256")
    source_meta = json.loads(SOURCE_MANIFEST.read_text())
    if sha256(REUSED_GENERATOR.read_bytes()) != REUSED_GENERATOR_SHA256:
        raise ValueError("Reviewed raw-UI generator changed; audit before regenerating")
    tt = TTFont(font_path)
    missing = set(CODEPOINTS) - set(tt.getBestCmap())
    if missing:
        raise ValueError(f"Source font lacks {len(missing)} required glyphs")
    if sha256((ROOT / "fonts/OFL.txt").read_bytes()) != source_meta["source"]["license_sha256"]:
        raise ValueError("Bundled OFL text differs from reviewed upstream license")
    c = HEADER + '#include "edge_fonts.h"\n\n'
    c += "#if LVGL_VERSION_MAJOR != 9 || LVGL_VERSION_MINOR != 5\n"
    c += '#error "CampusPulse V3 UI fonts target LVGL 9.5"\n#endif\n\n'
    c += "static const uint16_t edge_unicode_list[] = {\n"
    c += array([cp - 32 for cp in CODEPOINTS]) + "\n};\n\n"
    c += "static const lv_font_fmt_txt_cmap_t edge_cmaps[] = {{\n"
    c += f"    .range_start = 32, .range_length = {CODEPOINTS[-1] - 31},\n"
    c += "    .glyph_id_start = 1, .unicode_list = edge_unicode_list,\n"
    c += f"    .glyph_id_ofs_list = NULL, .list_length = {len(CODEPOINTS)},\n"
    c += "    .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,\n}};\n\n"
    stats, previews = {}, {}
    for size in SIZES:
        font = ImageFont.truetype(str(font_path), size, layout_engine=ImageFont.Layout.BASIC)
        glyphs = [raster(font, cp) for cp in CODEPOINTS]
        top = min(bottom - glyph.height for glyph, _, bottom, _ in glyphs)
        bottom = max(bottom for _, _, bottom, _ in glyphs)
        line_height = bottom - top
        bitmap = bytearray()
        descriptors = ["    {0}, /* Reserved missing-glyph ID */"]
        for cp, (glyph, x, glyph_bottom, advance) in zip(CODEPOINTS, glyphs):
            y = -glyph_bottom
            if glyph.width and glyph.height:
                if cp == 32:
                    raise ValueError("Unexpected visible space glyph")
                line_top = line_height - bottom - glyph.height - y
                assert 0 <= line_top and line_top + glyph.height <= line_height
                assert 0 <= x and x + glyph.width <= advance
            else:
                assert cp == 32, f"Unexpected empty glyph U+{cp:04X}"
            assert len(bitmap) < (1 << 20) and advance * 16 < (1 << 12)
            descriptors.append(
                f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {advance * 16}, "
                f".box_w = {glyph.width}, .box_h = {glyph.height}, .ofs_x = {x}, "
                f".ofs_y = {y}}}, /* U+{cp:04X} */"
            )
            bitmap.extend(pack(glyph))
        c += f"static LV_ATTRIBUTE_LARGE_CONST const uint8_t edge_bitmap_{size}[] = {{\n"
        c += array(bitmap) + "\n};\n\n"
        c += f"static const lv_font_fmt_txt_glyph_dsc_t edge_glyphs_{size}[] = {{\n"
        c += "\n".join(descriptors) + "\n};\n\n"
        c += f"static const lv_font_fmt_txt_dsc_t edge_dsc_{size} = {{\n"
        c += f"    .glyph_bitmap = edge_bitmap_{size}, .glyph_dsc = edge_glyphs_{size},\n"
        c += "    .cmaps = edge_cmaps, .kern_dsc = NULL, .kern_scale = 0,\n"
        c += "    .cmap_num = 1, .bpp = 4, .kern_classes = 0,\n"
        c += "    .bitmap_format = LV_FONT_FMT_TXT_PLAIN, .stride = 0,\n};\n\n"
        c += f"const lv_font_t edge_font_{size} = {{\n"
        c += "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,\n"
        c += "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,\n"
        c += f"    .line_height = {line_height}, .base_line = {bottom},\n"
        c += "    .subpx = LV_FONT_SUBPX_NONE, .kerning = LV_FONT_KERNING_NONE,\n"
        c += "    .static_bitmap = 1,\n"
        c += "    .underline_position = -1, .underline_thickness = 1,\n"
        c += f"    .dsc = &edge_dsc_{size},\n}};\n\n"
        stats[str(size)] = {
            "font_pixel_size": size, "line_height": line_height, "base_line": bottom,
            "bitmap_bytes": len(bitmap), "max_advance": max(g[3] for g in glyphs),
            "max_glyph_width": max(g[0].width for g in glyphs),
            "max_glyph_height": max(g[0].height for g in glyphs),
            "geometry_check": "all ink fits in line height and advance",
        }
        previews[size] = glyphs
    h = HEADER + '#pragma once\n#include "lvgl.h"\n\n#ifdef __cplusplus\nextern "C" {\n#endif\n\n'
    h += "\n".join(f"extern const lv_font_t edge_font_{size};" for size in SIZES)
    h += "\n\n#ifdef __cplusplus\n}\n#endif\n"
    files = {ROOT / "main/edge_fonts.c": c, ROOT / "main/edge_fonts.h": h}
    metadata = {
        "format_version": 1, "derived_font_names": ["CampusPulse V3 UI 12", "CampusPulse V3 UI 14", "CampusPulse V3 UI 16"],
        "license": "OFL-1.1", "copyright": source_meta["copyright"], "source": source_meta["source"],
        "generator": {"script": "firmware/waveshare-v3/tools/generate_ui_fonts.py",
                      "sha256": sha256(Path(__file__).read_bytes()),
                      "reused_from": "firmware/waveshare-raw/tools/generate_ui_fonts.py",
                      "reused_from_sha256": REUSED_GENERATOR_SHA256,
                      "pillow": pillow_version,
                      "fonttools": fontTools.__version__, "freetype": features.version("freetype2"),
                      "layout": "BASIC", "bitmap_format": "LVGL 9.5 fmt_txt uncompressed 4bpp, stride=0",
                      "rasterization": "direct at each requested size; no bitmap scaling"},
        "coverage": {"count": len(CODEPOINTS), "ascii": "U+0020..U+007E inclusive", "ui_text": UI_TEXT,
                     "codepoints": [f"U+{cp:04X}" for cp in CODEPOINTS],
                     "sha256": sha256("".join(chr(cp) for cp in CODEPOINTS).encode())},
        "sizes": stats,
        "outputs": {str(path.relative_to(ROOT)): sha256(text.encode()) for path, text in files.items()},
    }
    files[ROOT / "fonts/manifest.json"] = json.dumps(metadata, ensure_ascii=False, indent=2) + "\n"
    return files, metadata, previews


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--scan", action="append", type=Path, default=[])
    parser.add_argument("--preview", type=Path)
    args = parser.parse_args()
    for path in args.scan:
        missing = {ord(c) for c in path.read_text() if ord(c) > 127} - set(CODEPOINTS)
        if missing:
            raise SystemExit("Missing codepoints in " + str(path) + ": " + ", ".join(f"U+{cp:04X}" for cp in sorted(missing)))
    files, metadata, previews = generate(args.font)
    for path, text in files.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Generated file differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.preview:
        cols, cell_w, cell_h = 24, 26, 30
        rows = math.ceil(len(CODEPOINTS) / cols)
        sheet = Image.new("L", (cols * cell_w, (rows + 1) * cell_h * len(SIZES)), 255)
        draw = ImageDraw.Draw(sheet)
        for index, size in enumerate(SIZES):
            y0 = index * (rows + 1) * cell_h
            draw.text((4, y0 + 4), f"Native {size}px", fill=0)
            for i, (glyph, _, _, _) in enumerate(previews[size]):
                sheet.paste(glyph.point(lambda v: 255 - v * 17),
                            ((i % cols) * cell_w + 3, y0 + cell_h + (i // cols) * cell_h + 3))
        # BMP has no EXIF/XMP/IPTC or comments; this is an optional local QA file.
        sheet.save(args.preview, format="BMP")
    print(json.dumps({"mode": "check" if args.check else "write", "coverage": metadata["coverage"]["count"],
                      "sizes": metadata["sizes"]}, ensure_ascii=False))


if __name__ == "__main__":
    main()
