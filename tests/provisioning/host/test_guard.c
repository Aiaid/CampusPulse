#include "cp_provision_guard.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>
static void fill(cp_settings_t *s) {
    s->version = 1;
    strcpy(s->node_id, "cp_001122aabbcc"); strcpy(s->ssid, "test-network");
    strcpy(s->password, "test-password"); strcpy(s->device_token, "cpd_test-fixture-only");
    strcpy(s->api_origin, "https://pulse.anend.net");
}
int main(void) {
    assert(cp_provision_uuid_v4("11111111-2222-4333-8444-555555555555"));
    assert(cp_provision_uuid_v4("aaaaaaaa-bbbb-4ccc-bddd-eeeeeeeeeeee"));
    const char *bad[] = { "11111111-2222-3333-8444-555555555555", "11111111-2222-4333-7444-555555555555", "11111111-2222-4333-c444-555555555555", "111111112222-4333-8444-555555555555", "------------------------------------", "11111111-2222-4A33-8444-555555555555", "11111111-2222-4333-8444-555555555555x", "" };
    for (unsigned i = 0; i < sizeof(bad)/sizeof(bad[0]); i++) assert(!cp_provision_uuid_v4(bad[i]));
    assert(!cp_provision_uuid_v4(NULL));
    uint8_t context[44]; for (unsigned i = 0; i < sizeof(context); i++) context[i] = i;
    char pin[9],next_pin[9],ap[13],nonce[33],changed[13],next_nonce[33];uint8_t salt[16],next_salt[16];
    assert(cp_provision_session_secrets("00112233445566778899aabbccddeeff", context, sizeof(context), pin, ap, nonce, salt));
    /* Expected values independently generated by Node/OpenSSL HMAC-SHA256. */
    assert(!strcmp(pin,"17090949"));
    assert(!strcmp(ap,"TCFDBHKBJGAD"));
    assert(!strcmp(nonce,"7d46c14f9959eea5b52c7612fd8ef2b6"));
    const uint8_t expected_salt[]={0x0c,0xe8,0xa1,0x12,0x3c,0x72,0x76,0x18,0x04,0xaa,0x1a,0x5c,0xfd,0x14,0x84,0x71};assert(!memcmp(salt,expected_salt,16)); assert(strcmp(ap, nonce));
    context[43]++;
    assert(cp_provision_session_secrets("00112233445566778899aabbccddeeff", context, sizeof(context), next_pin, changed, next_nonce, next_salt)); assert(strcmp(ap, changed)); assert(strcmp(nonce, next_nonce));
    context[43]--;
    assert(cp_provision_session_secrets("10112233445566778899aabbccddeeff", context, sizeof(context), next_pin, changed, next_nonce, next_salt)); assert(strcmp(ap, changed));
    assert(!cp_provision_session_secrets("00112233445566778899aabbccddeeFF", context, sizeof(context), next_pin, changed, next_nonce, next_salt));
    assert(!cp_provision_session_secrets("00112233445566778899aabbccddeeff", context, 15, next_pin, changed, next_nonce, next_salt));
    bool leading_zero=false;
    for(unsigned n=0;n<256;n++) { context[43]=(uint8_t)n;assert(cp_provision_session_secrets("00112233445566778899aabbccddeeff",context,sizeof(context),pin,ap,nonce,salt));assert(strlen(pin)==8&&strlen(ap)==12&&strlen(nonce)==32);if(pin[0]=='0')leading_zero=true;for(unsigned i=0;i<8;i++)assert(pin[i]>='0'&&pin[i]<='9');for(unsigned i=0;i<12;i++)assert(strchr("23456789ABCDEFGHJKLMNPQRSTUVWXYZ",ap[i])); }
    assert(leading_zero);
    cp_settings_t first, second; memset(&first, 0xa5, sizeof(first)); memset(&second, 0x5a, sizeof(second)); fill(&first); fill(&second);
    uint8_t a[32], b[32]; assert(cp_provision_settings_digest(&first, a)); assert(cp_provision_settings_digest(&second, b)); assert(cp_provision_digest_equal(a,b));
    /* Every persisted candidate field participates; struct padding does not. */
    for (unsigned i = 0; i < 6; i++) {
        fill(&second);
        switch(i) { case 0: second.version++; break; case 1: second.node_id[3]='f'; break; case 2: second.ssid[0]='x'; break; case 3: second.password[0]='x'; break; case 4: second.device_token[4]='x'; break; case 5: second.api_origin[8]='x'; break; }
        assert(cp_provision_settings_digest(&second,b)); assert(!cp_provision_digest_equal(a,b));
    }
    fill(&first); fill(&second); strcpy(first.ssid,"ab"); strcpy(first.password,"c"); strcpy(second.ssid,"a"); strcpy(second.password,"bc");
    assert(cp_provision_settings_digest(&first,a)); assert(cp_provision_settings_digest(&second,b)); assert(!cp_provision_digest_equal(a,b));
    memset(second.password,'x',sizeof(second.password)); assert(!cp_provision_settings_digest(&second,b));
    puts("Provision guard: UUIDv4 rejection, HMAC domains/context/key, immutable candidate digest and length framing passed."); return 0;
}
